const messages = {
  "zh-CN": zhMessages,
  "en-US": enMessages,
} as const;

function formatMessage(message: MessageResolver, values?: TranslationValues) {
  if (typeof message === "function") {
    return message(values ?? {});
  }

  return message.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = values?.[key];
    return value === undefined || value === null ? "" : String(value);
  });
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  values?: TranslationValues,
) {
  return formatMessage(messages[locale][key] ?? zhMessages[key], values);
}

export function getCurrentLocale(): AppLocale {
  return resolveAppLocale(useSettingsStore.getState().language, getSystemLanguage());
}

export function tCurrent(key: TranslationKey, values?: TranslationValues) {
  return translate(getCurrentLocale(), key, values);
}

export function useI18n() {
  const language = useSettingsStore((state) => state.language);
  const setSettings = useSettingsStore((state) => state.setSettings);
  const locale = resolveAppLocale(language, getSystemLanguage());

  const t = useMemo(
    () => (key: TranslationKey, values?: TranslationValues) => translate(locale, key, values),
    [locale],
  );

  return {
    language,
    locale,
    setLanguage: (nextLanguage: AppLanguageSetting) => setSettings({ language: nextLanguage }),
    t,
  };
}

